const MS_DAY = 86400000;

export function iso(offsetDays: number): string {
  const base = new Date();
  base.setHours(12, 0, 0, 0);
  return new Date(base.getTime() + offsetDays * MS_DAY).toISOString().slice(0, 10);
}

